# Python 中的 __name__ 和 if __name__ == "__main__"
# 适合初学者的学习笔记
#
# 核心用途：
# 判断当前 Python 文件是被直接运行，还是被其他文件 import。
#
# 注意：
# __name__ 是 Python 自动设置的特殊变量。
# 直接运行文件时，__name__ 通常等于 "__main__"；
# 被其他文件 import 时，__name__ 通常等于模块名称。


# ============================================================
# 1. 查看 __name__
# ============================================================

print("当前模块的名称是：", __name__)

# 如果直接运行这个文件，输出通常是：
# 当前模块的名称是： __main__


# ============================================================
# 2. if __name__ == "__main__" 的基本用法
# ============================================================

def hello():
    print("Hello World!")


if __name__ == "__main__":
    # 只有直接运行这个文件时，才会执行这里的代码。
    hello()


# ============================================================
# 3. 为什么需要它？
# ============================================================
#
# 假设有两个文件：
#
# 文件一：calculator.py
#
# def add(a, b):
#     return a + b
#
# if __name__ == "__main__":
#     print("Calculator Started")
#
#
# 文件二：main.py
#
# import calculator
# print(calculator.add(10, 20))
#
# 直接运行 calculator.py：
# Calculator Started
#
# 运行 main.py：
# 30
#
# 原因：
# - 直接运行 calculator.py 时，__name__ == "__main__"，条件成立。
# - main.py import calculator 时，calculator.py 中的 __name__ 是 "calculator"，
#   所以条件不成立；但 add() 函数仍然可以被调用。
#
# 提醒：import 模块时，模块中不在函数或条件判断里的顶层代码仍会执行。
# 因此，通常把只想在直接运行时执行的启动代码放进这个判断中。


# ============================================================
# 4. 常见项目写法
# ============================================================

def main():
    print("Inventory Management System")
    # 可以在这里调用菜单函数、创建对象或启动程序。


if __name__ == "__main__":
    main()


# ============================================================
# 5. 重点整理
# ============================================================
#
# 直接运行文件：
#     __name__ == "__main__"
#
# 通过 import 导入文件：
#     __name__ 通常等于模块名称，例如 "calculator"
#
# if __name__ == "__main__":
#     main()
#
# 意思是：
# 只有直接运行这个文件时，才调用 main()。
#
# 它不是每个 Python 文件都必须写的，但当项目拆分成多个 .py 文件时很有用。
